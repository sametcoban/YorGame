"""Original CC0 loopable chapter drones and ambience; standard-library synthesis only."""
import math,random,struct,wave,hashlib,json,sys
from pathlib import Path
out=Path(sys.argv[1]);out.mkdir(parents=True,exist_ok=True)
rate=22050;seconds=12;report=[]
for theme in range(6):
 for family in ['Music','Ambience']:
  rng=random.Random(9810+theme);smooth=0;pcm=[];root=[55,61.735,65.406,73.416,82.407,98][theme]
  for i in range(rate*seconds):
   t=i/rate;fade=min(1,t/.4,(seconds-t)/.4)
   if family=='Music':
    value=sum(math.sin(2*math.pi*root*r*t+.015*math.sin(t*1.1))*a for r,a in [(1,.10),(1.189207,.06),(1.498307,.04)])*(.8+.2*math.sin(t*.55))
   else:
    smooth=.97*smooth+.03*rng.uniform(-1,1);value=smooth*.55*(.65+.35*math.sin(t*.7))
    phase=t%(2.2+theme*.15);value+=math.sin(2*math.pi*root*8*phase)*.035*math.exp(-phase*7)
   pcm.append(round(value*fade*32767))
  name=family+str(theme);path=out/(name+'.wav')
  with wave.open(str(path),'wb') as w:w.setnchannels(1);w.setsampwidth(2);w.setframerate(rate);w.writeframes(struct.pack('<'+'h'*len(pcm),*pcm))
  report.append({'name':name,'duration':seconds,'peak':max(abs(x) for x in pcm)/32767,'sha256':hashlib.sha256(path.read_bytes()).hexdigest()})
(out/'AUDIO_REPORT.json').write_text(json.dumps(report,indent=2)+'\n')
(out/'CREDITS.md').write_text('# Original chapter audio\n\nAll twelve music/ambience loops are original procedural audio generated by Tools/build_chapter_audio.py and dedicated to the public domain under CC0 1.0. No paid assets or third-party recordings. Each file is mono 22,050 Hz PCM; the report records checksums.\n')
print('Generated twelve original CC0 chapter loops')
